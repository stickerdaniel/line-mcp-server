import { execFile } from 'node:child_process';
import { chmodSync, cpSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { tempRoot } from './fake-line.ts';

const repo = fileURLToPath(new URL('..', import.meta.url));

/**
 * Stands in for `uvx --from fastmcp==4.1.0 fastmcp generate-cli <url> line_cli.py -f`
 * and writes what FastMCP 4.1.0 writes for the fixture: the URL with the
 * fixture's random port, and commands that name the script by file name.
 */
const fakeUvx = `#!/bin/sh
url=$5
cat >line_cli.py <<EOF
#!/usr/bin/env python3
"""CLI for 127.0.0.1 MCP server.

Generated by: fastmcp generate-cli $url
"""

import json
import sys

# Modify this to change how the CLI connects to the MCP server.
CLIENT_SPEC = '$url'

app = cyclopts.App(name="127.0.0.1", help="CLI for 127.0.0.1 MCP server")
EOF
cat >SKILL.md <<'EOF'
---
name: "127.0.0.1-cli"
description: "CLI for the 127.0.0.1 MCP server. Call tools, list resources, and get prompts."
---

# 127.0.0.1 CLI

## Tool Commands

### status

Session health.

\`\`\`bash
uv run --with fastmcp python line_cli.py call-tool status
\`\`\`
EOF
`;

/** A checkout at `dir`: the generator and its config copied, sources and packages linked. */
function checkout(dir: string): string {
	mkdirSync(dir, { recursive: true });
	cpSync(join(repo, 'scripts'), join(dir, 'scripts'), { recursive: true });
	for (const file of ['package.json', '.prettierrc']) cpSync(join(repo, file), join(dir, file));
	for (const link of ['src', 'node_modules']) symlinkSync(join(repo, link), join(dir, link));
	return dir;
}

function generate(dir: string, bin: string): Promise<{ skill: string; cli: string }> {
	return new Promise((resolve, reject) => {
		execFile(
			'bash',
			[join(dir, 'scripts', 'gen-cli.sh')],
			{ cwd: tempRoot(), env: { ...process.env, PATH: `${bin}:${process.env.PATH}` } },
			(error, _stdout, stderr) => {
				if (error) return reject(new Error(stderr));
				const skill = join(dir, 'skills', 'line-mcp');
				resolve({
					skill: readFileSync(join(skill, 'SKILL.md'), 'utf-8'),
					cli: readFileSync(join(skill, 'scripts', 'line_cli.py'), 'utf-8')
				});
			}
		);
	});
}

describe('gen-cli.sh', () => {
	it('writes the same skill and CLI from checkouts at different paths', async () => {
		const root = tempRoot();
		const bin = join(root, 'bin');
		mkdirSync(bin);
		writeFileSync(join(bin, 'uvx'), fakeUvx);
		chmodSync(join(bin, 'uvx'), 0o755);

		const first = await generate(checkout(join(root, 'line-mcp')), bin);
		const second = await generate(checkout(join(root, 'another place', 'clone')), bin);

		expect(second).toEqual(first);
		expect(JSON.stringify(first)).not.toContain(root);
		expect(first.skill).toContain(
			'uvx --from fastmcp==4.1.0 python "<skill-dir>/scripts/line_cli.py" call-tool status'
		);
		expect(first.cli).toContain('Generated by: fastmcp generate-cli http://127.0.0.1:47822/mcp');
	}, 60_000);
});
